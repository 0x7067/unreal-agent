#!/usr/bin/env python3
"""Emit UNTRUSTED finite-cover proof terms, checked against product.bend.
No Python result is assumed: decode, initial, every edge, and safety normalize
in Bend. Even a buggy/incomplete enumerator cannot prove a missing reducer edge.
"""
import argparse
from pathlib import Path

EVENTS = ('Tick', 'StatusInvisible', 'StatusVisible', 'UpdateOneAwaiting',
          'UpdateOneTerminal', 'UpdateTwoAwaiting', 'UpdateTwoTerminal',
          'UpdateInvisible', 'UpdateVisible', 'Crash', 'Stutter')
EMPTY = ('Absent', 'Absent')
READY = ('Ready', 'Ready')
INITIAL = ('Translate', 0, False, EMPTY, EMPTY, False, (False, False), False, False)
FIXED = (False, False, False)


def put(xs, i, v):
    return tuple(v if k == i else x for k, x in enumerate(xs))


def step(s, e, cfg=FIXED):
    pc, i, co, la, lo, ls, added, bc, bk = s
    sc, st, so = cfg
    if e == 'Crash':
        return ('Replay', 0, co, la, EMPTY, False, (False, False), bc, bk)
    if e == 'Tick':
        if pc == 'Translate': pc, i = 'Install', 0
        elif pc == 'Install':
            if i == 2: pc, ls = 'AppendStatus', True
            else: lo, i = put(lo, i, 'Ready'), i + 1
        elif pc == 'AppendStatus':
            co, la, pc = co or not sc, la if sc else READY, 'StatusReturn'
        elif pc == 'StatusReturn': pc, i = 'Guard', 0
        elif pc == 'Guard':
            if i == 2: pc = 'Idle'
            elif lo[i] == 'Terminal' and not st: i += 1
            else: pc = 'Add'
        elif pc == 'Add' and i < 2:
            bc, bk = bc or not co, bk or lo[i] == 'Terminal' or lo[i] != la[i]
            added, pc, i = put(added, i, True), 'Guard', i + 1
        elif pc == 'AppendUpdate': la, pc = put(la, i, lo[i]), 'UpdateReturn'
        elif pc == 'UpdateReturn': pc = 'Idle'
        elif pc == 'Replay':
            if i == 2: pc, i, ls = 'Overlay', 0, co
            else: lo, i = put(lo, i, 'Ready') if co else lo, i + 1
        elif pc == 'Overlay':
            if i == 2: pc, i = 'Guard' if ls else 'Translate', 0
            else: lo, i = put(lo, i, la[i]) if co and not so else lo, i + 1
    elif e.startswith('Status') and pc == 'AppendStatus':
        visible = e == 'StatusVisible'
        co, la, pc = co or visible, READY if visible else la, 'Stopped'
    elif e.startswith('UpdateOne') or e.startswith('UpdateTwo'):
        o = 0 if e.startswith('UpdateOne') else 1
        v = 'Awaiting' if e.endswith('Awaiting') else 'Terminal'
        if pc == 'Idle' and co and added[o] and (lo[o], v) in {
                ('Ready', 'Awaiting'), ('Ready', 'Terminal'), ('Awaiting', 'Terminal')}:
            pc, i, lo = 'AppendUpdate', o, put(lo, o, v)
    elif e in ('UpdateInvisible', 'UpdateVisible') and pc == 'AppendUpdate':
        la, pc = put(la, i, lo[i]) if e == 'UpdateVisible' else la, 'Stopped'
    return pc, i, co, la, lo, ls, added, bc, bk


def explore(cfg=FIXED, stop_bad=False):
    states, ids, paths = [INITIAL], {INITIAL: 0}, {INITIAL: []}
    for s in states:
        for e in EVENTS:
            t = step(s, e, cfg)
            if t not in ids:
                ids[t] = len(states)
                states.append(t)
                paths[t] = paths[s] + [e]
                if stop_bad and (t[-1] or t[-2]): return paths[t], t
    return states, ids


def b(v): return 'True{}' if v else 'False{}'
def core(s):
    pc, i, co, la, lo, ls, added, bc, bk = s
    snap = lambda p: 'P.Snapshots{' + ', '.join('P.' + x + '{}' for x in p) + '}'
    return ('P.Core{P.' + pc + '{}, P.' + ('One', 'Two', 'End')[i] + '{}, '
            + ', '.join((b(co), snap(la), snap(lo), b(ls),
                         'P.Flags{' + ', '.join(map(b, added)) + '}', b(bc), b(bk))) + '}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if checked artifacts are stale; do not write')
    args = parser.parse_args()
    root = Path(__file__).resolve().parent
    def emit(name, content):
        path = root / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Stale generated artifact: {path}; run {Path(__file__).name}")
        else:
            path.write_text(content)
    states, ids = explore()
    assert all(not s[-1] and not s[-2] for s in states)
    cert = ['# Generated by generate_certificate.py; checked, not trusted.',
            'import Base', 'import ./product.bend as P', '', 'type Index is Data:']
    cert += [f'  S{k}{{}}' for k in range(len(states))]
    cert += ['', 'def decode(i: Index) -> P.Core:', '  match i:']
    cert += [f'    case S{k}{{}}: {core(s)}' for k, s in enumerate(states)]
    cert += ['', '# Explicit finite relational invariant on unrestricted Core records.',
             'def Invariant(s: P.Core) -> Type:',
             '  &i: Index -> {decode(i) == s : P.Core}', '']
    emit('certificate.bend', '\n'.join(cert))
    proof = ['# Every concrete edge is checked against the independent-field reducer.',
             'import Base', 'import ./product.bend as P',
             'import ./certificate.bend as C', '']
    for e in EVENTS:
        proof += [f'def edge{e}(i: C.Index) -> C.Invariant(P.next(P.fixed(), P.{e}{{}}, C.decode(i))):', '  match i:']
        proof += [f'    case C.S{k}{{}}: (C.S{ids[step(s, e)]}{{}}, {{==}})' for k, s in enumerate(states)]
        proof += ['']
    proof += ['def closure(e: P.Boundary, i: C.Index) -> C.Invariant(P.next(P.fixed(), e, C.decode(i))):', '  match e:']
    proof += [f'    case P.{e}{{}}: edge{e}(i)' for e in EVENTS]
    proof += ['', 'def indexSafe(i: C.Index) -> {P.safe(C.decode(i)) == True{} : Bool}:', '  match i:']
    proof += [f'    case C.S{k}{{}}: {{==}}' for k in range(len(states))]
    proof += ['', 'def indexConsistent(i: C.Index) -> {P.consistent(C.decode(i)) == True{} : Bool}:', '  match i:']
    proof += [f'    case C.S{k}{{}}: {{==}}' for k in range(len(states))]
    emit('closure.bend', '\n'.join(proof) + '\n')
    # Genuine mutant execution witnesses from initial(), not supplied audits.
    wit = ['# Generated finite execution witnesses; all computations rechecked in Bend.',
           'import Base', 'import ./product.bend as P', '']
    for name, cfg in [('skipCommit', (True, False, False)),
                      ('skipTerminal', (False, True, False)),
                      ('skipOverlay', (False, False, True))]:
        events, final = explore(cfg, True)
        print(name, len(events), events)
        wit += [f'def {name}Config() -> P.Config: P.Config{{' + ', '.join(map(b, cfg)) + '}',
                f'def {name}Events() -> List<&2, P.Boundary>:',
                '  [' + ', '.join('P.' + e + '{}' for e in events) + ']', '']
    positive = {
        'twoOperationRecovery': ['Tick'] * 11 + ['UpdateOneAwaiting', 'Tick', 'Tick', 'UpdateTwoTerminal', 'Tick', 'Tick', 'Crash'] + ['Tick'] * 10,
        'visibleStatusRecovery': ['Tick'] * 4 + ['StatusVisible', 'Crash'] + ['Tick'] * 6,
        'invisibleStatusRecovery': ['Tick'] * 4 + ['StatusInvisible', 'Crash'] + ['Tick'] * 6,
        'visibleUpdateRecovery': ['Tick'] * 11 + ['UpdateTwoAwaiting', 'UpdateVisible', 'Crash'] + ['Tick'] * 6,
        'invisibleUpdateRecovery': ['Tick'] * 11 + ['UpdateTwoAwaiting', 'UpdateInvisible', 'Crash'] + ['Tick'] * 6,
        'partialOverlayCrash': ['Tick'] * 11 + ['UpdateTwoTerminal', 'Tick', 'Tick', 'Crash'] + ['Tick'] * 4 + ['Crash'] + ['Tick'] * 6,
    }
    for name, events in positive.items():
        final = INITIAL
        for e in events: final = step(final, e)
        wit += [f'def {name}Events() -> List<&2, P.Boundary>:',
                '  [' + ', '.join('P.' + e + '{}' for e in events) + ']',
                f'def {name}Expected() -> P.Core:', '  ' + core(final), '']
    emit('witnesses.bend', '\n'.join(wit))
    print(f'{len(states)} core states, {len(states) * len(EVENTS)} checked action edges')

if __name__ == '__main__': main()
