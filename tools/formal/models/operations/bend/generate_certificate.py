#!/usr/bin/env python3
"""Rebuild finite-core certificates; Python is NOT in the proof trust boundary.

Bend checks each concrete transition equality against product.bend. A bad
successor or omitted closure edge fails checking; completeness of this BFS is
not assumed. No crash budget: only the crash counter is projected away.
"""
import argparse
from collections import deque
from pathlib import Path

HERE = Path(__file__).resolve().parent
EVENTS = ['CreateErrDone', 'ProcessExit', 'CancelFails', 'RemoteFinishes',
          'HandlerCloses', 'Persist', 'Crash', 'Resume', 'Stutter']
# Independent fields, in exactly product.Core order. Checkpoints=(term,phase).
INIT = (True, 'CreateErr', 'Creating', False, True, False, False, True,
        (), (False, 'CreateErr'), (False, 'NoPhase'), 0, 0, 0)


def next_state(s, event, exclusive=True, skip=True):
    up, ph, ac, err, rm, rt, ru, ho, q, sh, re, n, sw, rw = s
    q = list(q)
    if event == 'CreateErrDone' and up and ph == 'CreateErr' and ac == 'Creating':
        if exclusive and err:
            ph, ac = 'PhaseDone', 'NoActive'
            q.append(('Shell', True, 'PhaseDone'))
        else:
            ph, ac, err, n = 'Process', 'Running', True, n + 1
            q.append(('Shell', False, 'Process'))
    elif event == 'ProcessExit' and up and ac == 'Running':
        ph, ac = 'PhaseDone', 'NoActive'
        q.append(('Shell', True, 'PhaseDone'))
    elif event == 'CancelFails' and up and rm and not rt:
        rt, ru = True, True
        q.append(('Remote', True, 'NoPhase'))
    elif event == 'RemoteFinishes' and up and rm and ho:
        if not rt:
            q.append(('Remote', True, 'NoPhase'))
        rm, rt, ru = False, True, False
    elif event == 'HandlerCloses' and up and ho:
        ho = False
        if rm and not (skip and rt):
            rt, ru = True, True
            q.append(('Remote', True, 'NoPhase'))
    elif event == 'Persist' and up and q:
        op, terminal, phase = q.pop(0)
        if op == 'Shell':
            sh, sw = (terminal, phase), sw + int(terminal)
        else:
            re, rw = (terminal, phase), rw + int(terminal)
    elif event == 'Crash' and up:
        up, ph, ac, rm, rt, ru, ho, q = False, 'NoPhase', 'NoActive', False, False, False, False, []
    elif event == 'Resume' and not up:
        up, ho, rm = True, True, not re[0]
        if not sh[0]:
            if sh[1] == 'Process':
                ph, ac, q = 'PhaseDone', 'NoActive', [('Shell', True, 'PhaseDone')]
            else:
                ph, ac, q = sh[1], 'Creating', []
    return up, ph, ac, err, rm, rt, ru, ho, tuple(q), sh, re, n, sw, rw


def boolean(b):
    return 'True{}' if b else 'False{}'


def checkpoint(c):
    return 'P.Checkpoint{' + boolean(c[0]) + ', P.' + c[1] + '{}}'


def core(s):
    up, ph, ac, err, rm, rt, ru, ho, q, sh, re, n, sw, rw = s
    queue = '[' + ', '.join('P.Update{P.' + o + '{}, ' + checkpoint((t, p)) + '}' for o, t, p in q) + ']'
    fields = [boolean(up), 'P.' + ph + '{}', 'P.' + ac + '{}']
    fields += list(map(boolean, [err, rm, rt, ru, ho]))
    fields += [queue, checkpoint(sh), checkpoint(re), f'{n}n', f'{sw}n', f'{rw}n']
    return 'P.Core{' + ', '.join(fields) + '}'


def emit(name, content, check):
    target = HERE / name
    if check:
        if not target.exists() or target.read_text() != content:
            raise SystemExit(f'{target}: stale certificate; regenerate and recheck Bend')
    else:
        target.write_text(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='check generated sources without writing')
    args = parser.parse_args()
    states, ids, todo = [INIT], {INIT: 0}, deque([INIT])
    while todo:
        s = todo.popleft()
        for e in EVENTS:
            t = next_state(s, e)
            if t not in ids:
                ids[t] = len(states)
                states.append(t)
                todo.append(t)
    print(f'{len(states)} core states; {len(states) * len(EVENTS)} checked closure edges; max FIFO length {max(len(s[8]) for s in states)}')
    # Public carrier/decode. Constructors enumerate independently stored states,
    # not operation lifecycle variants. None restrict product.Core.
    text = ['# Generated by generate_certificate.py; checked, not trusted.\nimport Base\nimport ./product.bend as P\n',
            'type Index is Data:']
    text += [f'  S{i}{{}}' for i in range(len(states))]
    text += ['\ndef decode(i: Index) -> P.Core:', '  match i:']
    text += [f'    case S{i}{{}}: {core(s)}' for i, s in enumerate(states)]
    text += ['\n# A finite-cover invariant on an unrestricted independent-field core.',
             'def Invariant(s: P.Core) -> Type:',
             '  &i: Index -> {decode(i) == s : P.Core}\n']
    emit('certificate.bend', '\n'.join(text), args.check)
    # One closure lemma per event avoids big dependent matching trees.
    text = ['# Generated transition equalities are checked against the executable reducer.',
            'import Base\nimport ./product.bend as P\nimport ./certificate.bend as C\n']
    for e in EVENTS:
        text += [f'def edge{e}(i: C.Index) -> C.Invariant(P.next(P.fixed(), P.{e}{{}}, C.decode(i))):', '  match i:']
        text += [f'    case C.S{i}{{}}: (C.S{ids[next_state(s, e)]}{{}}, {{==}})' for i, s in enumerate(states)]
        text += ['']
    text += ['def closure(e: P.Boundary, i: C.Index) -> C.Invariant(P.next(P.fixed(), e, C.decode(i))):', '  match e:']
    text += [f'    case P.{e}{{}}: edge{e}(i)' for e in EVENTS]
    text += ['\ndef indexSafe(i: C.Index) -> {P.safe(C.decode(i)) == True{} : Bool}:', '  match i:']
    text += [f'    case C.S{i}{{}}: {{==}}' for i in range(len(states))]
    for name in ['queueAccounting', 'durableHistory', 'queueBound']:
        text += [f'\ndef index{name}(i: C.Index) -> {{P.{name}(C.decode(i)) == True{{}} : Bool}}:', '  match i:']
        text += [f'    case C.S{i}{{}}: {{==}}' for i in range(len(states))]
    text += ['\ndef indexSpawns(i: C.Index) -> {Nat.is_le(P.spawnCount(C.decode(i)), 1n) == True{} : Bool}:', '  match i:']
    text += [f'    case C.S{i}{{}}: {{==}}' for i in range(len(states))]
    text += ['\ndef indexWrites(o: P.Op, i: C.Index) -> {Nat.is_le(P.terminalWrites(o, C.decode(i)), 1n) == True{} : Bool}:', '  match o:']
    for op in ['Shell', 'Remote']:
        text += [f'    case P.{op}{{}}:', '      match i:']
        text += [f'        case C.S{i}{{}}: {{==}}' for i in range(len(states))]
    emit('closure.bend', '\n'.join(text) + '\n', args.check)


if __name__ == '__main__':
    main()
